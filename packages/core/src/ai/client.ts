import { type ColumnMapping, validateMapping } from "../csv/mapping.js";
import type { ParsedCsv } from "../csv/parse.js";
import { bytesToHex, sha256, utf8ToBytes } from "../hash.js";
import { ValidationError } from "../validate.js";
import { buildMappingRequestBody } from "./request.js";
import {
  type AiSignature,
  type AttestationCheck,
  type PreflightAttestation,
  type SignatureCheck,
  checkPreflightAttestation,
  verifyAiSignature,
} from "./verify.js";

export const SIGNING_ALGO = "ecdsa";
/** One retry at most on a bad mapping (docs/05 credit rules). */
export const MAX_MAPPING_ATTEMPTS = 2;
const SIGNATURE_404_RETRIES = 3;

export type FetchLike = (url: string, init?: { method?: string; headers?: Record<string, string>; body?: string }) => Promise<{
  status: number;
  ok: boolean;
  text(): Promise<string>;
  arrayBuffer(): Promise<ArrayBuffer>;
}>;

export interface AiClientConfig {
  baseUrl: string;
  apiKey: string;
  model: string;
  fetch: FetchLike;
  /** 32 random bytes as 64 hex characters, generated by the caller for each run. */
  nonce: string;
  /** Wait between signature 404 retries; tests pass 0. */
  retryDelayMs?: number;
}

/** Everything the report builder and the verify page need about the one AI call of a run. */
export interface AiMappingEvidence {
  model: string;
  chatId: string;
  nonce: string;
  /** Exact bytes sent and received; hashes are over these. */
  requestBody: string;
  responseBytes: Uint8Array;
  requestSha256: string;
  responseSha256: string;
  /** null when the signature could not be fetched (the AI call is then unverified). */
  signature: AiSignature | null;
  signatureCheck: SignatureCheck;
  /** Raw preflight attestation text, stored as received. */
  attestationRaw: string;
  attestationCheck: AttestationCheck;
}

export interface AiMappingResult {
  mapping: ColumnMapping;
  evidence: AiMappingEvidence;
  /** Number of completions sent (1 or 2). */
  attempts: number;
}

/** The model's message content → validated mapping. Accepts a ```json fenced block. Code decides. */
export function parseMappingContent(content: unknown, headers: string[]): ColumnMapping {
  if (typeof content !== "string") throw new ValidationError("The AI reply has no text content");
  const text = content.trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    throw new ValidationError("The AI reply is not valid JSON");
  }
  return validateMapping(json, headers);
}

const UNVERIFIED: SignatureCheck = { kindOk: false, textOk: false, signerOk: false, verified: false };

/**
 * One column-mapping call with its evidence (docs/05 steps 1 and 4):
 * preflight attestation with our nonce → completion (exact bytes kept) → signature fetch → checks.
 * Throws ValidationError when no valid mapping came back after one retry (the UI then falls back to
 * manual mapping). A missing signature does not throw: the evidence says `verified: false`.
 * The caller enforces NEAR_AI_LIVE and the cache by csv_sha256.
 */
export async function requestColumnMapping(csv: ParsedCsv, cfg: AiClientConfig): Promise<AiMappingResult> {
  const base = cfg.baseUrl.replace(/\/$/, "");

  const attRes = await cfg.fetch(
    `${base}/attestation/report?signing_algo=${SIGNING_ALGO}&nonce=${cfg.nonce}&model=${encodeURIComponent(cfg.model)}&provider=near`,
    { headers: { Accept: "application/json", "x-no-aliasing": "true" } },
  );
  const attestationRaw = await attRes.text();
  let attestation: PreflightAttestation = {};
  if (attRes.ok) {
    try {
      attestation = JSON.parse(attestationRaw) as PreflightAttestation;
    } catch {
      /* unverified below */
    }
  }

  const requestBody = buildMappingRequestBody(csv, cfg.model);
  let lastError: Error = new ValidationError("The AI mapping call failed");
  for (let attempt = 1; attempt <= MAX_MAPPING_ATTEMPTS; attempt++) {
    const res = await cfg.fetch(`${base}/chat/completions`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${cfg.apiKey}`,
        "Content-Type": "application/json",
        "Accept-Encoding": "identity",
        "x-no-aliasing": "true",
      },
      body: requestBody,
    });
    const responseBytes = new Uint8Array(await res.arrayBuffer());
    if (!res.ok) {
      lastError = new ValidationError(`NEAR AI Cloud returned HTTP ${res.status}`);
      continue;
    }
    let mapping: ColumnMapping;
    let chatId: string;
    try {
      const completion = JSON.parse(new TextDecoder().decode(responseBytes)) as {
        id?: unknown;
        choices?: Array<{ message?: { content?: unknown } }>;
      };
      if (typeof completion.id !== "string" || completion.id === "") throw new ValidationError("The AI reply has no id");
      chatId = completion.id;
      mapping = parseMappingContent(completion.choices?.[0]?.message?.content, csv.headers);
    } catch (err) {
      lastError = err instanceof ValidationError ? err : new ValidationError("The AI reply could not be read");
      continue;
    }

    const signature = await fetchSignature(base, chatId, cfg);
    const requestBytes = utf8ToBytes(requestBody);
    const signatureCheck = signature
      ? await verifyAiSignature({ model: cfg.model, requestBytes, responseBytes, signature })
      : { ...UNVERIFIED, reason: "no signature available for this completion" };
    const attestationCheck = checkPreflightAttestation({
      attestation,
      nonce: cfg.nonce,
      signature: signature ?? { signing_address: "", signing_algo: "" },
    });
    return {
      mapping,
      attempts: attempt,
      evidence: {
        model: cfg.model,
        chatId,
        nonce: cfg.nonce,
        requestBody,
        responseBytes,
        requestSha256: bytesToHex(sha256(requestBytes)),
        responseSha256: bytesToHex(sha256(responseBytes)),
        signature,
        signatureCheck,
        attestationRaw,
        attestationCheck,
      },
    };
  }
  throw lastError;
}

/** A 404 is retried briefly; a 2xx with error_code, or anything else, means no signature. */
async function fetchSignature(base: string, chatId: string, cfg: AiClientConfig): Promise<AiSignature | null> {
  for (let i = 0; i <= SIGNATURE_404_RETRIES; i++) {
    const res = await cfg.fetch(`${base}/signature/${encodeURIComponent(chatId)}?signing_algo=${SIGNING_ALGO}`, {
      headers: { Authorization: `Bearer ${cfg.apiKey}`, Accept: "application/json" },
    });
    if (res.status === 404 && i < SIGNATURE_404_RETRIES) {
      await new Promise((r) => setTimeout(r, cfg.retryDelayMs ?? 1500));
      continue;
    }
    if (!res.ok) return null;
    try {
      const body = JSON.parse(await res.text()) as Partial<AiSignature> & { error_code?: unknown };
      if (body.error_code !== undefined) return null;
      if (typeof body.text !== "string" || typeof body.signature !== "string") return null;
      if (typeof body.signing_address !== "string" || typeof body.signing_algo !== "string") return null;
      return body as AiSignature;
    } catch {
      return null;
    }
  }
  return null;
}
